    ★ 官谱的 speedEvents 字段是 **value**（`{startTime, endTime, value}`），不是 start/end —— 移动/旋转/透明度那套才是 start/end。读错会把每段流速都当 0，整条线的音符全部挤在判定线上（屏幕上看起来就是「音符识别混乱」）。
    ★ 噪域数量大时编辑页按时间索引只画「此刻活着的」（实测同一时刻通常只有个位数到几百块），打歌时单帧最多画 24 块（只影响视觉，判定仍按全部区域算）。
    ★ 画面之外的东西不画（视锥剔除 / frustum culling）：噪域先按屏幕包围盒粗裁再截断数量（顺序不能反，否则前 N 块恰好都在屏幕外时屏幕上会一块不剩），像素网格的循环也只在屏幕范围内跑（行/列号仍按「距区域左上角第几格」算，否则画面一滚动噪点会整体跳位）。音符用的是**时间窗**：判定线的累积高度 H(t) 是单调的，所以「屏幕上能看到」等价于「音符时间落在 [H⁻¹(H(now) − 视野), H⁻¹(H(now) + 视野)] 里」，每条线每帧只反解 2 次、按 startMs 二分出起点终点，与音符总数无关。窗口一律往宽里放（视野 2.25 屏、按最小正流速、有 yControl 时再放宽 20 倍、yOffset 折算成额外时间余量、两端各加 900ms、长条按下界回退该线最长的长条长度、零流速的线直接放开成整谱、缩放极小导致跨度超过 1e7 时也直接放开），宁可多画也绝不漏画；上屏前原有的精确位置判定仍然保留。编辑模式的缩放（0.01~100）和打歌模式的缩放（0.6）都只是换 basePxPerMs，窗口会跟着自动缩放。
    ★ 判定线的三种类型由 `Texture` + `extended.textEvents` 决定，**不看 Name**：`Texture` 是 `line.png`（或没写）且没有文字事件 ⇒ 普通判定线（能放音符）；`line.png` + 有非空文字 ⇒ 文字线；`Texture` 是别的图 ⇒ 图片线。图片线/文字线是「素材」，上面**不能放音符**（点空白会提示「图片线是素材…」）。★ 图片线**也常挂 textEvents** 当副标题或贴纸，所以文字事件要按 `extended.textEvents` **逐条**保留（起止时刻 + start/end 字符串 + font + linkgroup），导入后原样写回导出：只记「第一个非空值」会让第一条为空串的线整条丢字。草稿里存成 `LX` 行。
9. AI（主界面）：左侧项目抽屉最下方的 AI 按钮，点=聊天，长按=接口设置。AI 能聊天、写文案、查资料（联网搜索 / 抓网页）、检测 BPM、执行 agent 操作（改设置、改项目信息、新建/复制/删除项目、只保留部分项目、开/关联机、导出、本地生成旋律歌曲、撤回）。
   改项目信息能改全部 11 个字段：曲名 name、曲师 composer、谱师 charter、难度 level、BPM、BPM 偏移、判定线位置、流速、延迟、横线数、竖线数。
10. AI（编辑页）：顶部「其他」按钮左边是「AI」按钮——**点一下**就打开 AI 抽屉；「AI」「其他」「导出谱面」这三个按钮**往任意方向滑**（上/下/左/右都可以）也能把抽屉拉下来（「其他」「导出」的普通点击还是各自原来的功能）。键盘弹出时抽屉不会收，输入框浮在键盘上沿。它和主界面那个 AI 一样开放：闲聊、聊新闻、写小说/文案、扒网页都行，只有你让它动谱面时才动谱面。抽屉贴在屏幕**右侧**、宽度 = 主界面左抽屉 + 右抽屉（458dp），上下铺满，点编辑区关闭。它和主界面是**同一个 AI、同一份聊天记录**，可以直接说「写一份 12 级谱，蓝键多点」「这里太密了」「把 BPM 应用上」；写谱是边收边铺；抽屉左上角的「撤回」**就是编辑页那个撤销按钮**（同一个撤销栈，手改的步骤也在里面，可连撤 200 步），**长按「撤回」= 重做**。它还能改**单个音符**（时间/位置/结束时间/键型 1蓝2长条3红4黄/所属判定线/正反面/真假）和**判定线关键帧**（新增、只改某一帧的流速或姿态、删掉某一帧）。编辑页「其他」二级窗口里另有「自动写谱 / 自动修谱 / 自动缤纷」，写谱前会检查设备延迟。★ 它也**能导出谱面**：说「导出谱面 / 给我谱面文件」它就打包成 .pez（zip：chart.json + 素材）存到手机的「下载/FRPHI/<曲名>.zip」，不用再点保存框，落盘位置会回在气泡里（右上角「导出谱面」按钮仍然是弹系统保存框，可以自己选位置）。
11. BPM 检测：主界面「判定线位置」输入框右边是「检测 BPM」按钮。点开先弹进度条（和导入谱面同一个弹窗样式，可取消），分析完弹结果：「一键应用」只改 BPM，「连偏移一起」同时把 BPM 偏移写成首个重拍的毫秒数。检测完全在手机本地跑（BPM Detect 算法：起音包络 → 节拍梳打分 → 倍频校正），不联网、不上传音频。编辑页 AI 里问 BPM 用的是同一套算法，回答后面有可点的「一键应用 BPM xxx」。
12. 没配置 AI 接口时，聊天框改为本地知识库检索：把问题里的词和内置功能说明逐行比对，返回相关原文；句子里出现 bpm / BPM / 节拍 / 曲速 时会自动跑本地 BPM 检测并返回结果；出现蓝键/谱/写 等词会调用本地节拍引擎写谱。配置接口后自动切换成 AI 回答（改由 AI 判断要不要调工具）。
13. 音符列表 / 单音符属性面板（编辑页顶部「其他」二级窗口里的「音符列表」按钮，默认关）：开启后点红框里的音符**不再删除**，改为在音符右侧弹出属性面板——左列「删除 / X镜像 / 关闭」，右侧可改键型、时间、X、速度、大小、透明度、纵向偏移、可见时间、判定范围（judgeArea）、音符颜色（tint）、特效颜色（tintHitEffects）、打击音效（hitsound）。框住多个音符时改的是**全部选中音符**：数值可选「设为」或「增减」，时间按差值整体平移；面板里的改动都能撤销/重做。
14. 判定线缩放：判定线/图片线/文字线的编辑面板右上角有「缩放」输入框（1=默认大小，图片线以"铺满谱面宽度"为 1），画布上也能拖四向绿色箭头。有关键帧时只改「选中帧 / 此刻正在生效的那一帧」的 scaleX/scaleY，**不会**把每一帧都刷成同一个值；没有关键帧时改整条线的基准缩放。缩放和关键帧都能撤销/重做。注意它和右下角「谱面缩放」（0.01~100，只影响预览大小）不是一回事。
15. 双押贴图（「其他」二级窗口「音符」组里的开关，默认关）：开启后只在**制作界面**把成对的音符换成 *_mh 贴图；Autoplay 打歌界面始终使用 mh 贴图，不受这个开关影响。
16. 视频背景（右侧窗口最右边的「视频」页签，对应 Phira extra.json 的 videos）：**全屏背景**，从设定的开始时间播放；每段只能调「开始（秒）/ 缩放方式（裁剪居中 / 完整显示 / 拉伸铺满）/ 透明度 / 昏暗度」，不能像图片线那样自由摆放。页脚「＋ 新建视频」= 从手机选视频导入（mp4/webm/mkv/mov/m4v/3gp/avi/ts），行短按=选中高亮、长按=打开属性编辑，左滑=复制、右滑=删除；新增/改属性/复制/删除都能撤销/重做。编辑页按当前时间在后台解码取帧显示，导出 .pez 时写进 extra.json，重新导入原样保留。
17. 玩家聊天（仅联机时）：在编辑页顶部「退出 / 保存 / 玩家列表」这一栏**往任意方向滑**，会从屏幕**左侧**拉出「玩家聊天」抽屉（和右侧 AI 抽屉同宽 458dp，气泡/输入条/键盘处理同款）。标题栏左边是「清空」、右边是标题「玩家聊天」；**没有「撤回」按钮**，聊天不进入撤销栈，不能撤销/重做。「清空」会先弹确认框，只清**本机**记录（SharedPreferences，最多保留最近 60 条），不发广播、不影响其他玩家。消息经局域网发给房间里的人；点抽屉外或按返回键收起。
18. 联机撤销：联机（含你写我打）时**撤销/重做不生效**（按钮还在，点了只提示「联机中不能撤销/重做」）；要撤销请先退出房间。对面推来的谱面**不会清掉本机的撤销栈**，退出房间后原来的撤销/重做照样能用。
   **退房 / 关房都默认保留房间谱面副本**：左滑绿框（客户端）弹「不保存副本 / 保存副本」，左滑蓝框（房主）弹「不保存副本 / 存到项目 / 存到副本」；**断网、被杀后台、被踢这种被动掉线，一律按「保存副本」处理**（绿框项目变成普通项目，谱面/音频/背景图都留着），只有自己点了「不保存副本」才真的丢掉。
19. 流速（可反复改）：编辑页「其他」二级窗口的「编辑」组里，BPM 输入框**下方**有「流速」输入框（和 BPM 输入框一样大）。随时可改、改多少次都行；改的是当前判定线（框住多条时一起改），同时写进项目设置，下次进来/导出都是这个值。
20. 你写我打（联机）：**玩家列表里右滑框色——第 1 个右滑的人=蓝方（写谱，只有一个），第 2 个及以后右滑的人全部=绿方（打谱，可以有很多个，能多人一起玩）**；再右滑一次=取消框色。框好之后**关掉玩家列表窗口**（点窗口外的空白处）= **发起开始请求**（顶部「玩家列表」按钮会被青色边框框住，表示在等回复），**不是立刻开始**：被框了色的人（含房主自己）都要在弹窗里点「接受 / 不接受」，**蓝方点「接受」才真正开始**，点「不接受」这一局就不开；**绿方不接受就不打**（接受几个就打几个）。开始后**打方进打歌界面自己打**，**写方留在编辑界面、画面照常跟着流动**（不进打歌界面、不自动演出）。打方**双击左上角**暂停；写方要暂停就按编辑界面右下角原来那个「暂停」按钮（再按「继续」恢复），点了打方跟着一起停/继续，打方的暂停菜单中间按钮下方显示「已打/一共」。打方点暂停菜单最左边的「<」= 双方一起退出这一局；写方也能从顶部「玩家列表」窗口左上角的「退出」结束这一局。
   **分数**：自己打 / 你写我打时右上角分数只算**真的打中的音符**（蓝键按下、黄键碰到、长条按到尾、红键划到位），漏掉不算分；分母是「从这一局开始的那个时间点往后还剩多少音符」，所以从中间开始打也能打到 100 万。AUTOPLAY 才是"到哪就该有多少分"。谱面本身不带分值（RPE/Phira 格式里没有每音符分数），FRPHI 的分数算法固定：命中数 ÷ 音符数 × 1,000,000。
   **打方判定规则（四种键各不相同，按 Phira 的垂直判定：只看判定时刻 + 横坐标，手指不用压在音符图形上）**：蓝键=点（手指按下那一刻命中）；黄键=碰（手指停在它的横坐标范围内就命中，不用按下）；长条=长按（头部要按下，之后一直有手指停在这个范围内到尾巴才算完，中途松手/移开/被噪域掐就断连）；红键=滑动点击（必须在它附近横向划一下，光按不动不算）。**噪域**：音符本身落在「亮着的真噪域」里的那一瞬间**打不中**（会被算漏），**警示区不算**（只会闪一下，照样能打）；手指落在亮着的真噪域里也会失效（Phigros 的断触），抬起来之前都判不了。
   **自己打（单机版「你写我打」）：点编辑界面右下角**（AUTOPLAY 那一格正上方、第一排倒数第二个）的 **「PLAY」按钮**就进入，判定规则和上面打方**完全一样**（四种键各自判定 + 噪域断触 + 同样的计分），不需要联机；**联机时点 PLAY 也只是本机自己打**，不会广播开始、不影响客户机。进去之后**变 STOP 的是 PLAY 按钮自己**（AUTOPLAY 保持原样不动），点 STOP 退出。PLAY 右边那一格是**「其他」**，和顶部「其他」是**同一个二级窗口**（面板还是从屏幕右上角弹出，位置不变）。
21. MC传谱（房主是 MC 模组时）：房间里还没有谱子时，主界面左抽屉里**右滑**一个项目，弹窗（右下角一排按钮：**取消 / MC传谱 / 复制 / 导出谱面**，「取消」一直都在，「MC传谱」紧挨在「复制」左侧）会多一个「MC传谱」；点它这个玩家变成**伪房主**——该项目变**紫框**，正下方出现一个**蓝色**联机副本，谱面立刻发给房间，**房间里所有客户端（含之后进来的人）立刻把谱面同步成这一份**。一次联机只能有一个伪房主、只能传一次；MC 关房或伪房主退出房间 = 关闭房间。
   **伪房主的权限（最高，压过 MC 端）**：伪房主一旦被选中，**MC 端就只是「提供服务器」，不再算房主**——玩家列表里 MC 那一行不再标 [房主]，伪房主那一行标 [伪房主] 并排在第一位。伪房主**左滑那个蓝色副本 = 关闭房间**（**紫色框项目只是本地传谱源，左滑它不关房**；关闭房间弹窗标题就写「关闭房间」，没有多余后缀）：先广播「closeroom」，所有 FRPHI 客户端（含 MC 端）立刻一起退出房间，各设备照「保留副本」的规则留一份谱面；伪房主也能在玩家列表里**左滑 MC 那一行把它踢掉（kickmc）**，效果是**服务端直接关闭、全员下线**（允许，但属于硬退，其他设备按断线处理）。只有伪房主能关房/踢 MC，其他客户端发这两种消息会被忽略。MC 多人游戏界面的「FRPHI联机」按钮**始终固定在屏幕右上角**，与「返回」等其它按钮没有任何关系（不读它们的坐标、不跟它们的尺寸变）。MC 模组里按 **A + Tab** 看 FRPHI 玩家列表；模组的联机界面有「快速服务端 / 快速客户端」，点了就在 60 秒内用局域网 UDP 广播（25567）互相找房。
22. 资源包编辑页（画贴图）：屏幕左右各有一条灰色拉条（和编辑界面同款：10dp 宽、纵向居中的圆角小条）——点**左**拉条开「剪贴板」窗口（只剩「取消框选」，复制/黏贴已经挪到左侧工具栏），点**右**拉条开「图层」窗口。**图层窗口放的是「当前这张贴图自己的图层」（PS 式），不是资源包的贴图列表**：列表顶层在上，每行前面「◉/○」是显示/隐藏，点一行 = 切到那层画（画笔/橡皮/油漆桶/黏贴只改当前层），长按行 = 改名；底部一排「＋ 删 ↑ ↓」＝新建空图层 / 删除当前层 / 上移 / 下移（至少要留一层）。新建/删除/移动/显隐/改尺寸都会清空撤销栈，笔画撤销只回退当前层。保存与导出时把所有**可见**层拍平成一张 PNG；图层本身另存在 app 私有目录（不往资源包里加文件），下次进编辑页还在。左侧工具栏「笔刷形状」那一栏最下面有「复制 / 黏贴」两个按钮（和正方形/三角形同一栏）。画布上**长按 0.5 秒**出方框，拖动框住一块区域（复制取的是「看到的」合成图）；有框时**双指捏合 = 原地缩放这块**（不是缩放画布），**点一下屏幕 = 关掉框**（不会留下笔迹）。框选/黏贴/缩放都能撤销。
